create or replace function public.manage_team_member(p_actor uuid,p_target uuid,p_role text,p_active boolean,p_clinic_id uuid) returns void
language plpgsql security definer set search_path='' as $$
declare m public.clinic_members;
begin
  perform 1 from public.clinics where id=p_clinic_id for update;
  if not exists(select 1 from public.clinic_members where clinic_id=p_clinic_id and user_id=p_actor and role='owner' and active) then raise exception 'Access denied' using errcode='42501';end if;
  if p_role is null or p_role not in ('owner','professional','reception') or p_active is null or (p_target=p_actor and (not p_active or p_role<>'owner')) then raise exception 'Invalid role' using errcode='22023';end if;
  select * into m from public.clinic_members where clinic_id=p_clinic_id and user_id=p_target for update;
  if m.role='owner' and m.active and (p_role<>'owner' or not p_active)
    and (select count(*) from public.clinic_members where clinic_id=p_clinic_id and role='owner' and active)<=1 then raise exception 'LAST_OWNER';end if;
  if (not p_active or p_role='reception') and exists(select 1 from public.appointments where clinic_id=p_clinic_id and provider_id=p_target and status='confirmed' and starts_at>now()) then raise exception 'MEMBER_HAS_APPOINTMENTS';end if;
  insert into public.clinic_members(clinic_id,user_id,role,active) values(p_clinic_id,p_target,p_role,p_active)
    on conflict(clinic_id,user_id) do update set role=excluded.role,active=excluded.active;
  if p_role='professional' then
    insert into public.clinic_practitioners(clinic_id,user_id) values(p_clinic_id,p_target) on conflict do nothing;
    insert into public.practitioner_specialties(clinic_id,user_id,specialty_id) values(p_clinic_id,p_target,'podologia') on conflict do nothing;
    insert into public.member_specialties(clinic_id,user_id,specialty_id,can_read,can_write,can_export,scope)
      values(p_clinic_id,p_target,'podologia',true,true,true,'assigned') on conflict do nothing;
  elsif p_role='reception' then
    update public.member_specialties set can_read=false,can_write=false,can_export=false where clinic_id=p_clinic_id and user_id=p_target;
    update public.clinic_practitioners set active=false where clinic_id=p_clinic_id and user_id=p_target;
  end if;
  insert into public.access_events(clinic_id,actor_id,subject_id,event,details) values(p_clinic_id,p_actor,p_target,'membership',jsonb_build_object('role',p_role,'active',p_active));
end;$$;

