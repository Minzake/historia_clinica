create function private.validate_podology_v1(p_record jsonb) returns void
language plpgsql set search_path='' as $$
declare v_patient jsonb;v_values jsonb;v_field text;v_item jsonb;v_birth date;v_date date;
begin
  if p_record is null or octet_length(p_record::text) > 2000000 or jsonb_typeof(p_record) <> 'object' then
    raise exception 'Invalid record' using errcode = '22023';
  end if;
  v_patient := p_record->'patient';
  v_values := p_record->'clinical';
  if jsonb_typeof(v_patient) is distinct from 'object' or jsonb_typeof(v_values) is distinct from 'object'
    or jsonb_typeof(p_record->'evolutions') is distinct from 'array' then
    raise exception 'Invalid record structure' using errcode = '22023';
  end if;
  foreach v_field in array array['fullName','historyNumber','dni','date','address','age','birthDate','phone','mobile','insurance',
    'occupation','emergencyContact','emergencyPhone','treatment','treatmentNotes','medication','sports','diet','alcohol','smoking','footwear','photoConsent','referredBy'] loop
    if jsonb_typeof(v_patient->v_field) is distinct from 'string' or length(v_patient->>v_field) > 2000 then
      raise exception 'Invalid patient field' using errcode = '22023';
    end if;
  end loop;
  foreach v_field in array array['usual','pressure','glucose','weight','height'] loop
    if jsonb_typeof(v_values->v_field) is distinct from 'string' or length(v_values->>v_field) > 2000 then
      raise exception 'Invalid clinical field' using errcode = '22023';
    end if;
  end loop;
  if length(v_values->>'pressure') > 40 or length(v_values->>'glucose') > 40
    or length(v_values->>'weight') > 10 or length(v_values->>'height') > 10 or length(v_patient->>'referredBy') > 80 then
    raise exception 'Clinical field too long' using errcode = '22023';
  end if;
  if length(v_patient->>'fullName') > 200 or length(v_patient->>'historyNumber') > 40
    or v_patient->>'treatment' not in ('unset','yes','no') or v_patient->>'photoConsent' not in ('unset','yes','no') then
    raise exception 'Invalid patient values' using errcode = '22023';
  end if;
  if (v_patient->>'date') !~ '^\d{4}-\d{2}-\d{2}$' or (v_patient->>'birthDate' <> '' and (v_patient->>'birthDate') !~ '^\d{4}-\d{2}-\d{2}$') then
    raise exception 'Invalid date format' using errcode = '22023';
  end if;
  v_date := (v_patient->>'date')::date;
  v_birth := nullif(v_patient->>'birthDate','')::date;
  if v_date > current_date or v_birth > v_date then raise exception 'Invalid date' using errcode = '22023'; end if;
  if v_birth is not null then
    v_patient := jsonb_set(v_patient, '{age}', to_jsonb(extract(year from age(v_date, v_birth))::integer::text));
  end if;
  if v_patient->>'age' <> '' and ((v_patient->>'age') !~ '^\d{1,3}$' or (v_patient->>'age')::integer > 125) then
    raise exception 'Invalid age' using errcode = '22023';
  end if;
  foreach v_field in array array['weight','height'] loop
    if v_values->>v_field <> '' then
      if replace(v_values->>v_field, ',', '.') !~ '^\d+(\.\d+)?$' then raise exception 'Invalid numeric value' using errcode = '22023'; end if;
      if replace(v_values->>v_field, ',', '.')::numeric <= 0 or replace(v_values->>v_field, ',', '.')::numeric > (case when v_field = 'weight' then 700 else 300 end) then
        raise exception 'Invalid numeric range' using errcode = '22023';
      end if;
    end if;
  end loop;
  if jsonb_typeof(v_patient->'antecedents') is distinct from 'array' or jsonb_typeof(v_patient->'vaccines') is distinct from 'array' then
    raise exception 'Invalid antecedents' using errcode = '22023';
  end if;
  if jsonb_array_length(v_patient->'antecedents') <> 18 or jsonb_array_length(v_patient->'vaccines') <> 3 then
    raise exception 'Invalid antecedent count' using errcode = '22023';
  end if;
  for v_item in select value from jsonb_array_elements((v_patient->'antecedents') || (v_patient->'vaccines')) loop
    if jsonb_typeof(v_item->'label') is distinct from 'string' or length(v_item->>'label') > 100
      or jsonb_typeof(v_item->'notes') is distinct from 'string' or length(v_item->>'notes') > 2000
      or jsonb_typeof(v_item->'id') is distinct from 'string' or length(v_item->>'id') > 40
      or coalesce(v_item->>'answer','') not in ('unset','yes','no') then
      raise exception 'Invalid antecedent value' using errcode = '22023';
    end if;
  end loop;
  if jsonb_array_length(p_record->'evolutions') > 500 then raise exception 'Too many evolutions' using errcode = '22023'; end if;
  for v_item in select value from jsonb_array_elements(p_record->'evolutions') loop
    if jsonb_typeof(v_item->'procedure') is distinct from 'string' or length(btrim(v_item->>'procedure')) not between 1 and 20000
      or coalesce(v_item->>'id','') !~ '^[0-9a-fA-F-]{36}$' or coalesce(v_item->>'date','') !~ '^\d{4}-\d{2}-\d{2}$' then
      raise exception 'Invalid evolution' using errcode = '22023';
    end if;
    if (v_item->>'date')::date > current_date or (v_item->>'date')::date < v_birth then
      raise exception 'Invalid evolution date' using errcode = '22023';
    end if;
  end loop;
  if (select count(*) <> count(distinct value->>'id') from jsonb_array_elements(p_record->'evolutions')) then
    raise exception 'Repeated evolution id' using errcode = '22023';
  end if;

end;$$;

create function private.validate_podology_questions(p_record jsonb) returns void
language plpgsql set search_path='' as $$
declare v_labels text[]:=array['Diabetes','VPP - NPP','Enfermedades cardíacas','Hipertensión','Hipotensión','Convulsiones','Asma','Alergias','VIH / Sida - Sífilis - Otras','Hepatitis','Tuberculosis','Infecciones','Fracturas / Esguinces','Luxaciones','Colesterol','Tiroides','Está anticoagulado','Otros (detallar)'];
  v_vaccines text[]:=array['Antitetánica','Hepatitis B','Otras (detallar)']; v_i integer;
begin
  if jsonb_typeof(p_record->'patient'->'antecedents') is distinct from 'array' or jsonb_typeof(p_record->'patient'->'vaccines') is distinct from 'array' then
    raise exception 'QUESTIONNAIRE_INVALID' using errcode='22023';
  end if;
  if jsonb_array_length(p_record->'patient'->'antecedents')<>18 or jsonb_array_length(p_record->'patient'->'vaccines')<>3 then
    raise exception 'QUESTIONNAIRE_INVALID' using errcode='22023';
  end if;
  for v_i in 0..17 loop
    if (p_record->'patient'->'antecedents')->v_i->>'id' is distinct from v_i::text or (p_record->'patient'->'antecedents')->v_i->>'label' is distinct from v_labels[v_i+1] then
      raise exception 'QUESTIONNAIRE_INVALID' using errcode='22023';
    end if;
  end loop;
  for v_i in 0..2 loop
    if (p_record->'patient'->'vaccines')->v_i->>'id' is distinct from 'v'||v_i::text or (p_record->'patient'->'vaccines')->v_i->>'label' is distinct from v_vaccines[v_i+1] then
      raise exception 'QUESTIONNAIRE_INVALID' using errcode='22023';
    end if;
  end loop;
end;$$;

create function private.normalize_patient_identity(p_identity jsonb) returns jsonb
language plpgsql set search_path='' as $$
declare v_field text;v_result jsonb:=p_identity;v_dni text;v_phone text;
begin
  if jsonb_typeof(p_identity) is distinct from 'object' or octet_length(p_identity::text)>12000
    or exists(select 1 from jsonb_object_keys(p_identity) k where k<>all(array['fullName','historyNumber','dni','birthDate','address','phone','mobile','insurance','occupation','emergencyContact','emergencyPhone'])) then raise exception 'Invalid identity' using errcode='22023';end if;
  foreach v_field in array array['fullName','historyNumber','dni','birthDate','address','phone','mobile','insurance','occupation','emergencyContact','emergencyPhone'] loop
    if jsonb_typeof(p_identity->v_field) is distinct from 'string' or length(p_identity->>v_field)>200 then raise exception 'Invalid identity field' using errcode='22023';end if;
    v_result:=jsonb_set(v_result,array[v_field],to_jsonb(btrim(p_identity->>v_field)));
  end loop;
  if length(v_result->>'fullName')<2 or length(v_result->>'historyNumber')>40 then raise exception 'Invalid identity' using errcode='22023';end if;
  v_dni:=regexp_replace(v_result->>'dni','[.\s-]','','g');
  if v_dni<>'' and v_dni!~'^[0-9]{6,10}$' then raise exception 'Invalid DNI' using errcode='22023';end if;
  v_result:=jsonb_set(v_result,'{dni}',to_jsonb(v_dni));
  if v_result->>'birthDate'<>'' and ((v_result->>'birthDate')!~'^\d{4}-\d{2}-\d{2}$' or (v_result->>'birthDate')::date>current_date) then raise exception 'Invalid birth date' using errcode='22023';end if;
  foreach v_field in array array['phone','mobile','emergencyPhone'] loop
    v_phone:=v_result->>v_field;
    if v_phone<>'' and (length(v_phone)>40 or v_phone!~'^\+?[0-9[:space:]().-]+$' or length(regexp_replace(v_phone,'[^0-9]','','g')) not between 6 and 20) then raise exception 'Invalid phone' using errcode='22023';end if;
  end loop;
  return v_result;
end;$$;

create function private.persist_patient_identity(p_clinic_id uuid,p_patient_id uuid,p_expected_version integer,p_identity jsonb) returns uuid
language plpgsql security definer set search_path='' as $$
declare p public.patients;v_identity jsonb:=private.normalize_patient_identity(p_identity);v_details jsonb;v_number text;v_next bigint;
begin
  v_details:=v_identity-array['fullName','dni','historyNumber'];v_number:=v_identity->>'historyNumber';
  if p_patient_id is null then
    if p_expected_version is distinct from 0 then raise exception 'CONFLICT_IDENTITY';end if;
    if v_number='' then
      loop
        update public.clinics set next_history_number=next_history_number+1 where id=p_clinic_id returning next_history_number-1 into v_next;
        v_number:='HC-'||lpad(v_next::text,greatest(6,length(v_next::text)),'0');
        exit when not exists(select 1 from public.patients where clinic_id=p_clinic_id and lower(history_number)=lower(v_number));
      end loop;
    end if;
    insert into public.patients(clinic_id,full_name,dni,history_number,details)
      values(p_clinic_id,v_identity->>'fullName',v_identity->>'dni',v_number,v_details) returning * into p;
  else
    select * into p from public.patients where id=p_patient_id and clinic_id=p_clinic_id for update;
    if not found then raise exception 'Access denied' using errcode='42501';end if;
    if v_number='' then v_number:=p.history_number;end if;
    if (p.full_name,p.dni,p.history_number,p.details) is distinct from (v_identity->>'fullName',v_identity->>'dni',v_number,v_details) then
      if p_expected_version is distinct from p.version then raise exception 'CONFLICT_IDENTITY';end if;
      if v_identity->>'birthDate'<>'' and exists(select 1 from public.clinical_encounters where chart_id in(select id from public.clinical_charts where patient_id=p.id) and date<(v_identity->>'birthDate')::date) then raise exception 'Invalid birth date' using errcode='22023';end if;
      update public.patients set full_name=v_identity->>'fullName',dni=v_identity->>'dni',history_number=v_number,details=v_details,version=version+1,updated_at=now() where id=p.id;
    end if;
  end if;
  return p.id;
end;$$;

create function public.save_clinical_chart(p_clinic_id uuid,p_patient_id uuid,p_specialty_id text,p_schema_version integer,
  p_expected_version integer,p_expected_identity_version integer,p_identity jsonb,p_data jsonb) returns jsonb
language plpgsql security definer set search_path='' as $$
declare v_id uuid;c public.clinical_charts;v_record jsonb;v_result jsonb;v_item jsonb;v_initial jsonb;
begin
  if p_specialty_id is distinct from 'podologia' or p_schema_version is distinct from 1 then raise exception 'UNSUPPORTED_CLINICAL_SCHEMA' using errcode='22023';end if;
  perform 1 from public.clinic_members m join public.member_specialties s on s.clinic_id=m.clinic_id and s.user_id=m.user_id
    join public.clinic_specialties cs on cs.clinic_id=s.clinic_id and cs.specialty_id=s.specialty_id and cs.enabled
    where m.clinic_id=p_clinic_id and m.user_id=auth.uid() and m.active and m.role<>'reception' and s.specialty_id=p_specialty_id and s.can_write;
  if not found then raise exception 'Access denied' using errcode='42501';end if;
  if p_patient_id is not null then
    perform 1 from public.patients where id=p_patient_id and clinic_id=p_clinic_id for update;
    if not found then raise exception 'Access denied' using errcode='42501';end if;
    select * into c from public.clinical_charts where clinic_id=p_clinic_id and patient_id=p_patient_id and specialty_id=p_specialty_id for update;
    if found and not private.can_access_chart(c.id,'write') then raise exception 'Access denied' using errcode='42501';end if;
  end if;
  if p_expected_version is distinct from coalesce(c.version,0) then raise exception 'CONFLICT';end if;
  if jsonb_typeof(p_data) is distinct from 'object' or octet_length(p_data::text)>2000000
    or exists(select 1 from jsonb_object_keys(p_data) k where k<>all(array['initial','clinical','evolutions'])) then raise exception 'Invalid clinical data' using errcode='22023';end if;
  if jsonb_typeof(p_data->'clinical') is distinct from 'object' or exists(select 1 from jsonb_object_keys(p_data->'clinical') k where k<>all(array['usual','pressure','glucose','weight','height'])) then raise exception 'Invalid clinical data' using errcode='22023';end if;
  v_initial:=p_data->'initial';
  if jsonb_typeof(v_initial) is distinct from 'object' or exists(select 1 from jsonb_object_keys(v_initial) k where k<>all(array['date','age','antecedents','vaccines','treatment','treatmentNotes','medication','sports','diet','alcohol','smoking','footwear','photoConsent','referredBy'])) then raise exception 'Invalid clinical data' using errcode='22023';end if;
  v_record:=jsonb_build_object('patient',v_initial||private.normalize_patient_identity(p_identity),'clinical',p_data->'clinical','evolutions',p_data->'evolutions');
  perform private.validate_podology_v1(v_record);perform private.validate_podology_questions(v_record);
  v_id:=private.persist_patient_identity(p_clinic_id,p_patient_id,p_expected_identity_version,p_identity);
  if c.id is null then
    insert into public.clinical_charts(clinic_id,patient_id,specialty_id,schema_version,initial_data,clinical_values,export_context)
      values(p_clinic_id,v_id,p_specialty_id,p_schema_version,v_initial,p_data->'clinical',(select settings from public.clinics where id=p_clinic_id)) returning * into c;
    insert into public.clinical_access_grants select p_clinic_id,c.id,auth.uid(),true,true,can_export,auth.uid(),now() from public.member_specialties where clinic_id=p_clinic_id and user_id=auth.uid() and specialty_id=p_specialty_id;
  else
    update public.clinical_charts set initial_data=v_initial,clinical_values=p_data->'clinical',version=version+1,updated_at=now(),
      export_context=(select settings from public.clinics where id=p_clinic_id) where id=c.id returning * into c;
  end if;
  if exists(select 1 from public.clinical_encounters e join jsonb_array_elements(p_data->'evolutions') i on e.id=(i->>'id')::uuid where e.chart_id<>c.id) then raise exception 'Access denied' using errcode='42501';end if;
  update public.clinical_encounters set archived_at=now(),updated_by=auth.uid() where chart_id=c.id and archived_at is null and id not in(select (value->>'id')::uuid from jsonb_array_elements(p_data->'evolutions'));
  insert into public.clinical_encounters(id,clinic_id,chart_id,date,procedure,position,created_by,updated_by)
    select (value->>'id')::uuid,p_clinic_id,c.id,(value->>'date')::date,value->>'procedure',(ordinality-1)::integer,auth.uid(),auth.uid()
    from jsonb_array_elements(p_data->'evolutions') with ordinality
    on conflict(id) do update set date=excluded.date,procedure=excluded.procedure,position=excluded.position,updated_by=auth.uid(),archived_at=null;
  v_result:=public.get_clinical_chart(v_id,p_specialty_id,false);
  insert into public.clinical_chart_versions(clinic_id,chart_id,version,schema_version,snapshot,recorded_by) values(p_clinic_id,c.id,c.version,p_schema_version,v_result-array['canWrite','canExport'],auth.uid());
  return v_result;
end;$$;

create or replace function public.save_patient_record(p_clinic_id uuid,p_patient_id uuid,p_expected_version integer,p_record jsonb) returns jsonb
language plpgsql security definer set search_path='' as $$
declare v_identity jsonb;
begin
