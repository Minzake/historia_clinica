create function public.get_clinical_chart(p_patient_id uuid,p_specialty_id text default 'podologia',p_export boolean default false,p_clinic_id uuid default null) returns jsonb
language plpgsql stable security definer set search_path='' as $$
declare c public.clinical_charts;p public.patients;
begin
  select * into c from public.clinical_charts where patient_id=p_patient_id and specialty_id=p_specialty_id and (p_clinic_id is null or clinic_id=p_clinic_id);
  if not found or not private.can_access_chart(c.id,case when p_export then 'export' else 'read' end) then raise exception 'Access denied' using errcode='42501';end if;
  select * into p from public.patients where id=c.patient_id and clinic_id=c.clinic_id;
  return jsonb_build_object('id',p.id,'chartId',c.id,'specialtyId',c.specialty_id,'schemaVersion',c.schema_version,
    'version',c.version,'identityVersion',p.version,'updatedAt',c.updated_at,
    'canWrite',private.can_access_chart(c.id,'write'),'canExport',private.can_access_chart(c.id,'export'),
    'patient',c.initial_data||p.details||jsonb_build_object('fullName',p.full_name,'dni',p.dni,'historyNumber',p.history_number),
    'clinical',c.clinical_values,'evolutions',coalesce((select jsonb_agg(jsonb_build_object('id',e.id,'date',e.date,'procedure',e.procedure) order by e.position,e.id)
      from public.clinical_encounters e where e.chart_id=c.id and e.archived_at is null),'[]'::jsonb))
    ||case when c.export_context is null then '{}'::jsonb else jsonb_build_object('exportContext',c.export_context) end;
end;$$;
