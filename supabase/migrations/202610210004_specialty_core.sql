      from public.member_specialties s join public.specialties sp on sp.id=s.specialty_id where s.clinic_id=m.clinic_id and s.user_id=m.user_id),'[]'::jsonb)) order by u.email)
    from public.clinic_members m join auth.users u on u.id=m.user_id left join public.clinic_practitioners p on p.clinic_id=m.clinic_id and p.user_id=m.user_id where m.clinic_id=p_clinic_id),'[]'::jsonb);
end;$$;


create function public.list_chart_access(p_clinic_id uuid,p_chart_id uuid) returns jsonb
language plpgsql stable security definer set search_path='' as $$
begin
  if not private.is_owner(p_clinic_id) or not exists(select 1 from public.clinical_charts where clinic_id=p_clinic_id and id=p_chart_id) then raise exception 'Access denied' using errcode='42501';end if;
  return coalesce((select jsonb_agg(jsonb_build_object('user_id',m.user_id,'email',u.email,'scope',s.scope,'allow_write',s.can_write,'allow_export',s.can_export,'can_read',coalesce(g.can_read,false),'can_write',coalesce(g.can_write,false),'can_export',coalesce(g.can_export,false)) order by u.email)
    from public.clinical_charts c join public.member_specialties s on s.clinic_id=c.clinic_id and s.specialty_id=c.specialty_id and s.can_read
    join public.clinic_members m on m.clinic_id=s.clinic_id and m.user_id=s.user_id and m.active and m.role<>'reception'
    join auth.users u on u.id=m.user_id left join public.clinical_access_grants g on g.chart_id=c.id and g.user_id=m.user_id where c.id=p_chart_id),'[]'::jsonb);
end;$$;
revoke all on function public.list_chart_access(uuid,uuid) from public,anon;
grant execute on function public.list_chart_access(uuid,uuid) to authenticated;

commit;
