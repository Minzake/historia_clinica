create function private.can_access_chart(p_chart_id uuid,p_action text) returns boolean
language sql stable security definer set search_path='' as $$
  select exists(select 1 from public.clinical_charts c
    join public.clinic_members m on m.clinic_id=c.clinic_id and m.user_id=auth.uid() and m.active
    join public.member_specialties s on s.clinic_id=m.clinic_id and s.user_id=m.user_id and s.specialty_id=c.specialty_id
    join public.clinic_specialties cs on cs.clinic_id=c.clinic_id and cs.specialty_id=c.specialty_id
    left join public.clinical_access_grants g on g.chart_id=c.id and g.user_id=m.user_id
    where c.id=p_chart_id and m.role<>'reception' and
      case p_action when 'read' then s.can_read and (s.scope='all' or g.can_read)
      when 'write' then cs.enabled and s.can_write and (s.scope='all' or g.can_write)
      when 'export' then s.can_export and (s.scope='all' or g.can_export) else false end);
$$;
